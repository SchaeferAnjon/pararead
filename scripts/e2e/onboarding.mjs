// 首次引导和收费页：新数据目录打开应该是引导；逐步点过去，第 4 步假装没装 MinerU 看下载进度再停掉，最后进文献库，从侧栏卡片打开收费页。
// node scripts/e2e/onboarding.mjs <新的数据目录>
import { close, launch, PAPER, shot, sleep } from './drive.mjs'

const { app, win } = await launch(process.argv[2])
const ev = (fn, ...a) => win.evaluate(fn, ...a)
win.on('pageerror', (e) => console.log('pageerror:', e.message))
win.on('console', (m) => m.type() === 'error' && console.log('console:', m.text().slice(0, 300)))
try {
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1280, 820))
  await sleep(1500)
  console.log('引导出现:', await win.locator('.onb').count())
  await shot(win, 'onb-1')
  await win.locator('.of .btn.primary').click()
  await sleep(400)
  await shot(win, 'onb-2')
  await win.locator('.choice', { hasText: '会员' }).first().click()
  await sleep(300)
  await win.locator('.choice .btn', { hasText: '看看会员' }).click()
  await sleep(2500)
  await shot(win, 'pricing')
  await win.keyboard.press('Escape')
  await sleep(300)
  console.log('收费页关了:', (await win.locator('.price').count()) === 0)
  await win.locator('.of .btn.primary').click()
  await sleep(400)
  await shot(win, 'onb-3')
  await win.locator('.of .btn.primary').click()
  await sleep(400)
  await shot(win, 'onb-4-installed')
  // 假装这台没装：看下载进度，再停掉
  await ev(() => window.api.setSettings({ mineruPath: '/nonexistent/mineru-kit' }))
  await sleep(500)
  await win.locator('.choice .btn', { hasText: '开始下载' }).click()
  await sleep(14000)
  await shot(win, 'onb-4-downloading')
  console.log('下载中:', JSON.stringify(await ev(() => window.api.mineruInstallState())).slice(0, 160))
  await ev(() => window.api.mineruStopInstall())
  await sleep(1500)
  console.log('停掉后:', (await ev(() => window.api.mineruInstallState())).phase)
  await win.locator('.of .btn.primary').click()
  await sleep(600)
  await shot(win, 'onb-5')
  // 第 5 步导入一篇（文件对话框点不了，直接走同一个接口）
  await ev((p) => window.api.importPdfs([p]), PAPER)
  await win.locator('.of .btn.primary', { hasText: '打开文献库' }).click()
  await sleep(1500)
  console.log('进了文献库:', await win.locator('.sb').count(), '论文行:', await win.locator('.row').count())
  console.log('onboarded:', (await ev(() => window.api.getSettings())).onboarded)
  await win.locator('.plan').click()
  await sleep(1500)
  console.log('侧栏卡片打开收费页:', await win.locator('.price').count())
  await shot(win, 'pricing-from-sidebar')
} finally {
  await close(app)
}
